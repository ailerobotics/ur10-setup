"""Generate ``params/camera_poses.sim.yaml`` from ``cell_layout.CAMERAS``.

The detector node looks up ``base_link -> <optical_frame>`` via tf2; the
human_safety launch publishes a static TF for every VALID entry in the poses
file. We use the loader's INLINE-transform form (translation + rotation), so the
TF the detector consumes is computed here from the very same look-at that places
the Isaac camera prim — they cannot drift apart.

Run: ``python3 sim/isaac_human/gen_sim_config.py`` (writes the yaml next to the
harness). The offline test ``tests/test_sim_config.py`` regenerates in a temp dir
and asserts the committed file is byte-identical, so a stale committed file fails
CI rather than silently feeding the detector a wrong pose.
"""
from __future__ import annotations

import os

from cell_layout import CAMERAS

_HEADER = """\
# GENERATED by sim/isaac_human/gen_sim_config.py from cell_layout.CAMERAS.
# Do not edit by hand — edit cell_layout.py and regenerate. Inline
# base_link -> <optical_frame> static transforms for the SIMULATED cameras, in
# the human_safety camera_poses loader's inline form (translation + rotation
# xyzw). Because these come from the same look-at that places the Isaac camera
# prim, the detector's TF is exactly the pose Isaac renders from.
"""


def render() -> str:
    lines = [_HEADER, "cameras:"]
    for cam in CAMERAS:
        t, q = cam.base_to_optical()
        lines.append(f"  {cam.role}:")
        lines.append("    calibrated: true")
        lines.append("    parent: base_link")
        lines.append(f"    child: {cam.optical_frame}")
        lines.append("    translation: [%s, %s, %s]" % tuple(
            f"{v:.6f}" for v in t))
        lines.append("    rotation: [%s, %s, %s, %s]" % tuple(
            f"{v:.6f}" for v in q))
        lines.append(f"    source: sim_look_at:{cam.role}")
    return "\n".join(lines) + "\n"


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "params", "camera_poses.sim.yaml")
    with open(out, "w") as f:
        f.write(render())
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
